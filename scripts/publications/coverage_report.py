"""Write docs/CONTENT_COVERAGE.md from the committed publication index and showcase manifest.

Per family: editions, date range, largest gap vs. cadence, mean/min review score, desk verdicts,
flag counts and the share of `_estimated` editions. Regenerate after a backfill:

    python scripts/publications/coverage_report.py
"""
from __future__ import annotations

import argparse
import collections
import json
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
INDEX = ROOT / "showcase" / "data" / "publications" / "index.json"
MANIFEST = ROOT / "showcase" / "manifest.json"
CONFIG = ROOT / "config" / "publications.yaml"
OUT = ROOT / "docs" / "CONTENT_COVERAGE.md"


def _gap(dates: list[date]) -> tuple[int, str]:
    if len(dates) < 2:
        return 0, "—"
    gaps = [((b - a).days, a, b) for a, b in zip(dates, dates[1:])]
    days, a, b = max(gaps)
    return days, f"{a.isoformat()} → {b.isoformat()}"


def build() -> str:
    cfg = yaml.safe_load(CONFIG.read_text())
    index = json.loads(INDEX.read_text())["editions"]
    pages = json.loads(MANIFEST.read_text())["dashboards"]
    lines = ["# Content coverage", "",
             "Generated by `scripts/publications/coverage_report.py` from `showcase/data/publications/index.json` and "
             "`showcase/manifest.json`; do not hand-edit. All schema editions are synthetic (`_estimated: true`, "
             "docs/PROVENANCE.md §2a) — illustrative scenario, not investment advice.", "",
             "## Schema editions (Apr–Nov 2026 backfill)", "",
             "| Family | Cadence | Editions | First | Last | Largest gap (days, limit 2×cadence) | Judge mean / min | Desk verdicts | Flags | Estimated share |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    by = collections.defaultdict(list)
    for e in index:
        by[e["family"]].append(e)
    for family, fam_cfg in cfg["families"].items():
        es = sorted(by.get(family, []), key=lambda e: e["date"])
        if not es:
            continue
        dates = [date.fromisoformat(e["date"]) for e in es]
        gap, _ = _gap(dates)
        scores = [e["review_score"] for e in es if "review_score" in e]
        verdicts = collections.Counter(e.get("review_verdict", "—") for e in es)
        flags = collections.Counter(f for e in es for f in e.get("flags", []))
        est = sum(1 for e in es if e.get("_estimated")) / len(es)
        lines.append(f"| {family} | {fam_cfg['cadence']} | {len(es)} | {dates[0]} | {dates[-1]} | "
                     f"{gap} (≤ {2 * fam_cfg['cadence_days']}) | "
                     f"{sum(scores) / len(scores):.3f} / {min(scores):.3f} | "
                     f"{', '.join(f'{k} {v}' for k, v in sorted(verdicts.items()))} | "
                     f"{', '.join(f'{k} ×{v}' for k, v in sorted(flags.items())) or '—'} | {est:.0%} |")
    lines += ["", "## All dated showcase pages by family (manifest)", "",
              "Includes earlier hand-made generations kept as templates. Gaps are between consecutive dated pages.", "",
              "| Family | Dated pages | First | Last | Largest gap |", "|---|---|---|---|---|"]
    dated = collections.defaultdict(set)
    for p in pages:
        if p.get("date") and len(p["date"]) == 10:
            dated[p["family"]].add(date.fromisoformat(p["date"]))
    for family in sorted(dated, key=lambda f: -len(dated[f])):
        ds = sorted(dated[family])
        days, span = _gap(ds)
        lines.append(f"| {family} | {len(ds)} | {ds[0]} | {ds[-1]} | {days} d ({span}) |")
    fams = collections.Counter(p["family"] for p in pages)
    lines += ["", f"Manifest: {len(pages)} pages, {len(fams)} families, {fams.get('other', 0)} classified `other`.", "",
              "## Known gaps", "",
              "- No live market or fundamentals feed: every figure comes from the seeded path "
              "`data/scenarios/2026H2_path.json` and the illustrative inputs in `config/valuation/coverage_2026.yaml`.",
              "- Credit memo and deep dive families have templates and schema support but no backfilled editions.",
              "- DCF targets use `core/engine/valuation_utils.py` as-is (fixed 2.5% terminal growth, 5-year horizon); "
              "the review layer flags most DCF names as `target_out_of_range` vs. their reference prices.",
              "- Market Mayhem weeks with an existing `newsletters/market_mayhem_2026*.md` narrative link it as unverified; "
              "older 2025–early-2026 hand-made pages are not converted to schema records.",
              "- Reviews are deterministic and offline; the LLM desk / red-team / judge path is off (`config/publication_review.yaml`)."]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/CONTENT_COVERAGE.md is stale")
    args = ap.parse_args()
    text = build()
    if args.check:
        return int(not OUT.exists() or OUT.read_text() != text)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
